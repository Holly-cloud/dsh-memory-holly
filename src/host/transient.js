/**
 * dsh-memory · 自主捕获的**第二道闸**：确定性「事实分类器」。
 *
 * ## 为什么要有它
 * 提示词（`EXTRACT_PROMPT` / `EXTRACT_FOCUSED_PROMPT`）里已经写死了「不要记」清单，
 * 但提示词**不是保证**：模型照样会把「用户与助手约好用 propose 流程处理那条记忆」
 * 「身边另有一位 teammate 在并行工作」「助手认为…」这类**本次会话的工作安排 / 工具协作状态 /
 * 助手自己的立场**抽成「事实」，写进记忆库并污染检索（用户 2026-10-07 原话：
 * 「自主捕获的记忆，不能什么都录入，一些偏临时的事实描述是可以忽略的」）。
 *
 * 所以抽取之后、**写库 / 入待审区之前**再过一道纯函数分类：`looksTransient(text)`。
 * 本模块**只有纯函数**：不碰 ctx、不碰库、不调 LLM，可以直接单测。
 *
 * ## 三分类（2026-10-07 升级：二分类 → 三分类）
 * 旧的二分类只有「临时 / 不临时」，于是**用技术词表述的长期决定**被误杀：
 * 「用户采纳了…只出变更单、不直接改库」「用户和助手约定仓管的所有改动先进入独立待审区」
 * 「用户决定记忆抽取暂定由自己手动启动」——它们命中 `变更单` / `待审区` / `暂定` 就被静默丢掉。
 * 用户的口径是「**偏临时**的事实描述可以忽略」——「用技术词表述的长期决定」不是临时事实。
 * 现在改成三分类，判据刻意**收窄**，并且**技术词（`变更单` / `待审区` / `验收` / `重启` /
 * `panel` / `工具`）单独出现不再构成临时**：
 *
 * - **`transient`（丢）**：纯**进度 / 协作 / 会话态** —— `teammate` / `subagent` / `子代理`、
 *   以「助手 / 我」为主语的立场与动作、`正在` / `刚刚` / `这轮` / `本次会话` / `接下来` /
 *   `待办` / `进度`、`跑通了 N 条`、`约好用…流程`、`约定：…`（冒号清单）。
 *   这类句子**没有长期事实主体**；它们**不受长期锚点豁免**（先判，命中即丢）。
 * - **`durable`（保留）**：命中**长期信号**一律保留，**即使同时出现技术词**：
 *   `决定` / `采纳` / `拍板` / `统一` / `约定`（须有「用户 / 宝宝 / 小屿」之类人称主体，
 *   且不能是 `约定：` 冒号清单）/ `偏好` / `习惯` / `要求` / `记住` / `基准` / `长期` /
 *   日期锚点（`\d{4}-\d{2}-\d{2}`、`\d{2}-\d{2}`）/ 偏好习惯、身份归属、关系类词。
 * - **`uncertain`（拿不准）**：既不是上述会话态句式、又没有明确长期锚点 → **交审阅，不丢**
 *   （`lib/index.js` 的 `runCapture` 把它并成一个待审批次；`memory_extract` 本就进待审区）。
 *
 * 判定顺序：**会话态（硬）→ 长期锚点（durable）→ 当下状态 / 约定冒号清单（弱）→ uncertain**。
 * 这个顺序是刻意的：拿「漏判」换「不误杀」——宁可把一条会话态留在库里 / 送进待审区，
 * 也不许把一条长期决定静默丢掉。
 *
 * ## 已知边界（启发式，如实说明）
 * - 它按**句子**判，不看上下文：「我建议」在转录里指的是助手，但一条独立的记忆句子里的
 *   「我建议」也可能真是用户说的 —— 这种情况会漏判（留下）。宁可漏，不可误杀；
 * - 弱规则里的 `目前` 仍是状态词：「用户目前在杭州出差」这类**暂时**状态会被丢掉（正确），
 *   而「用户目前在杭州工作」靠 `工作是` 豁免留下；把「工作」写成「上班」就救不回来；
 * - `约定：`（带冒号）一律按会话清单处理（`约定：先改代码，再更新文档`）—— 长期约定若写成
 *   冒号句式（「用户和宝宝约定：以后每年生日一起拍照」）会被 `每年 / 生日` 这类长期锚点救回来，
 *   但若清单里没有任何长期锚点就会被判 transient（`用户和助手约定：先改代码再重启`）；
 * - 以「助手 / 我」**作句首主语**（行首 / `。；：！？` / 括号后）且后接动词的句子一律 transient：
 *   逗号接出来的第二个小句（「…，助手会照它推断默认取值」）**不算**，否则前半句的长期事实
 *   （「用户有自己一贯的风格」）会被一起判死；真出现「助手」是**用户给某个人起的称呼**这类
 *   罕见写法仍会误杀（已知、未修，值得时把 `助手` 从主语表里摘掉）；
 * - **技术词不再单独构成 transient**，所以「这条事实还躺在待审区」「这次工具调用返回了 0 条」
 *   这类**没有长期事实主体、但也没命中会话态句式**的句子会落到 `uncertain`（进待审区等人看），
 *   而不再被静默丢掉 —— 这是刻意的：宁多一道人眼，不误删。
 *
 * @module dsh-memory/host/transient
 */

/**
 * 人称主体：`约定` 这类词只有在句子里有人称主体时才算长期信号
 * （「约定：先改代码」是会话清单，「用户和宝宝约定每年生日一起拍照」是长期事实）。
 *
 * @type {RegExp}
 */
const PERSON_RE = /用户|宝宝|小屿|本人|主人/;

/**
 * **会话 / 协作态（硬规则）**：命中即 `transient`，**不受长期锚点豁免**。
 *
 * 顺序即优先级；`id` 只进 `hit` 供人读与测试断言，正则都不带 `g`（`test()` 无 `lastIndex` 状态）。
 *
 * @type {{ id: string, re: RegExp }[]}
 */
const SESSION_STATE_RULES = [
  // 工具 / 协作态：某个 teammate / subagent / 子代理在做什么。
  { id: 'teammate', re: /\bteammates?\b/i },
  { id: 'subagent', re: /\bsub-?agents?\b/i },
  { id: '子代理', re: /子代理/ },
  // 会话 / 任务边界与待办。
  { id: '会话边界', re: /本次会话|本次任务|本轮会话|这一轮|这轮|本回合|这个回合/ },
  // ⚠️ 「待办 / 待处理」**不在这条硬规则里**：它既是进度状态，又是面板里的页面名 ——
  // 用户 2026-10-07 真实踩到：「用户习惯只看待办与检索页面」被这条规则**丢掉**。
  // 进度清单的「待办：…」形态挪到弱规则；两个词单独出现则落 uncertain（不丢、交人眼）。
  { id: '待办进度', re: /接下来|下一步|TODO/i },
  // 助手自身的立场与动作（「助手认为…」「我建议…」「助手实现完成后…」）。
  // ⚠️ 必须在**句首 / 分句句首**（行首、句号、分号、冒号、括号后）才算主语：
  //   - 不能是「用户采纳了助手建议的四条语义」（`助手` 前面是「了」）—— 那是用户的长期决定；
  //   - 也不能是「，助手会…」这种**逗号接出来的第二个小句** —— 前半句讲的是用户的长期风格
  //     （真实库里就有「用户有自己一贯的风格（house-style），助手会照它推断默认取值」），
  //     逗号后的助手小句不该把前半句的长期事实一起判死。
  {
    id: '助手自述',
    re: /(?:^|[。；：！？\s（(])(?:助手|我)(?:认为|觉得|建议|打算|提出|准备|负责|需要|应该|会|将|已|正在|把|完成|实现|做|给出|输出|继续|承诺|承认|坚持|倾向|要求)/,
  },
  // 协作安排：「约好用…流程」「按…流程」「走…流程」「流程处理」。（`约定` 单独见弱规则）
  { id: '协作安排', re: /约好(?:用|了|的)?|流程处理|按[^，。；]{0,10}流程|走[^，。；]{0,10}流程/ },
  // 带数字的进度汇报：「跑通了 265 条 / 通过 201 例」。
  { id: '进度汇报', re: /(?:跑通|通过|完成|搞定|做完)了?\s*\d+\s*(?:条|例|个|项)/ },
  // 纯进度汇报：句子以「已完成 / 已实现 / 跑通了」开头（长期事实一般有主语，不会这样开头）。
  {
    id: '纯进度',
    re: /^\s*(?:已完成|已实现|已改完|已修复|已提交|已跑通|已重建|已部署|跑通了|已经完成|搞定了|做完了)/,
  },
];

/**
 * **长期信号（durable）**：命中即保留，即使句子里同时出现技术词。
 *
 * `needPerson: true` 的规则要求句子里出现人称主体（`PERSON_RE`）。
 *
 * @type {{ id: string, re: RegExp, needPerson?: boolean }[]}
 */
const DURABLE_RULES = [
  // 决策 / 拍板 / 约定：长期决定的核心词（旧的误杀全出在这里没有豁免）。
  { id: '长期决策', re: /决定了|决定以后|定下来|决定|拍板|采纳|统一|长期|基准|记住|要求/ },
  // 「约定」必须有人称主体，且**不能**是「约定：」冒号清单（那是会话步骤，见弱规则）。
  { id: '长期约定', re: /约定(?![:：])/, needPerson: true },
  // 偏好 / 习惯 / 在意的点。
  { id: '偏好习惯', re: /偏好|习惯|喜欢|最爱|忌口|口味|作息|过敏|在意|希望|倾向/ },
  // 日期锚点：具体到日期的决定 / 里程碑。
  { id: '日期锚点', re: /\d{4}-\d{2}-\d{2}|\d{2}-\d{2}/ },
  // 身份 / 归属 / 周期 / 关系 / 家人。
  {
    id: '身份关系',
    re: /老家|祖籍|定居|住在|职业|工作是|称呼|名字叫|生日|纪念日|每年|每月|每周|每天|一直|从小|结婚|爱人|老婆|老公|孩子|女儿|儿子|父亲|母亲|爸妈|宠物|养的|养了|同事|同学|朋友|室友/,
  },
];

/**
 * **版本绑定的事实**：**界面结构**（有几个页签 / 哪些按钮 / 卡片怎么排）+ 数量枚举。
 *
 * 这类事实**必须带时间或版本锚点**：没有锚点的「用户要求面板只保留四个页签」在今天是对的，
 * 面板一改版就变成假的，而后来读它的人只会当成永久通则（用户 2026-10-07 亲自点出这个危险）。
 *
 * 口径只收**界面结构词**，刻意**不含** `入口 / 端口 / 版本 / 路径 / 目录 / 模型名`：
 * 实测（全库扫描）后者会把「所有落库只通过 reviewKeeperPlan 这一个入口」这类**真决定**圈进来
 * （这里的「入口」是架构写入口，不是界面），误报比收益大。
 */
const VERSION_BOUND_RE = /页签|标签页|按钮|控件|卡片|下拉|菜单|界面|面板|布局/;
/** 数量枚举：「4 个」「四张」「二十条」。 */
const COUNT_RE = /\d+\s*(个|条|张|颗|项|种|块|行)|[一二三四五六七八九十]\s*(个|条|张|项|种|块)/;
/** 时间 / 版本锚点：有它就算把话说圆了。 */
const ANCHOR_RE =
  /20\d{2}[-/年]|\d{1,2}[-/月]\d{1,2}|截至|当时|那版|改版前|改版后|目前|今天|昨天|这版|当前版本/;

/**
 * **弱规则**：只有句子里**没有**长期锚点时才算 `transient`。
 *
 * - `约定[:：]`：冒号清单式的会话安排（`约定：先改代码，再更新文档`）；
 * - `正在 / 刚刚 / 目前 / 暂定 / 暂时 / 进度`：当下状态副词与进度词。
 *
 * `现在` / `当前` 这类太常出现在长期事实里的词**刻意不收**，避免误杀。
 *
 * @type {{ id: string, re: RegExp }[]}
 */
const WEAK_RULES = [
  { id: '约定清单', re: /约定[:：]/ },
  // 「待办：…」才是进度清单；光出现「待办 / 待处理」这两个词不算（面板里就是页面名）。
  { id: '待办清单', re: /待办[:：]|待处理[:：]|待办清单|待办事项/ },
  { id: '当下状态', re: /正在|刚刚|目前|暂定|暂时|进度/ },
];

/**
 * 分类一条「抽出来的事实」。
 *
 * - 非字符串 / 空串一律 `durable`（**放行**）：过滤器只对事实文本生效，别的输入不背锅，
 *   顺手丢数据才是事故（真正的落库入口本来就会忽略非字符串）。
 *
 * @param {unknown} text 一条事实（正常情况下是字符串）
 * @returns {{ verdict: 'durable' | 'transient' | 'uncertain', hit: string }}
 *   `verdict` 是三分类结论；`hit` 是可读的命中理由（`规则id:命中片段`），`uncertain` 为 `''`
 */
export function looksTransient(text) {
  const value = typeof text === 'string' ? text : text == null ? '' : String(text);
  // 非字符串 / 空串一律放行（durable）：过滤器只对事实文本生效，别的输入不背锅。
  if (typeof text !== 'string' || value.trim() === '') return { verdict: 'durable', hit: '' };

  // ① 会话 / 协作态（硬）：不受长期锚点豁免 —— 它们是**本次会话**的状态，不是长期事实。
  for (const rule of SESSION_STATE_RULES) {
    const match = rule.re.exec(value);
    if (match !== null) return { verdict: 'transient', hit: `${rule.id}:${match[0]}` };
  }

  // ①.5 版本绑定的事实：**排在长期信号之前、不受它豁免**。
  // 「用户要求面板只保留四个页签」会命中 `要求`（长期信号）而直存 —— 但面板一改版它就是假的。
  // 没有时间 / 版本锚点就一律 `uncertain`：不丢，但必须有人看一眼（或补上锚点）。
  if (VERSION_BOUND_RE.test(value) && COUNT_RE.test(value) && !ANCHOR_RE.test(value)) {
    return { verdict: 'uncertain', hit: '版本绑定:缺时间锚点' };
  }

  // ② 长期信号：命中即保留（哪怕同时出现技术词）。
  const hasPerson = PERSON_RE.test(value);
  for (const rule of DURABLE_RULES) {
    if (rule.needPerson === true && !hasPerson) continue;
    const match = rule.re.exec(value);
    if (match !== null) return { verdict: 'durable', hit: `${rule.id}:${match[0]}` };
  }

  // ③ 弱规则：没有长期锚点的当下状态 / 冒号清单 → 临时。
  for (const rule of WEAK_RULES) {
    const match = rule.re.exec(value);
    if (match !== null) return { verdict: 'transient', hit: `${rule.id}:${match[0]}` };
  }

  // ④ 拿不准 → 交审阅（不丢）。
  return { verdict: 'uncertain', hit: '' };
}

/**
 * 对一批事实做三分类（`looksTransient` 的批量版）。
 *
 * 非法元素（非字符串）**原样留在 `kept` / `staged` 里**：过滤器只负责「分类」，
 * 不该顺手丢数据；真正的落库入口本来就会忽略非字符串。
 *
 * @param {unknown[]} facts 抽出来的事实数组
 * @returns {{ kept: unknown[], dropped: { text: string, hit: string }[],
 *   deferred: { text: string, hit: string }[], staged: unknown[] }}
 *   - `kept`：durable（保留、可直存），保持原顺序；
 *   - `dropped`：transient（丢弃），带命中理由；
 *   - `deferred`：uncertain（拿不准、交待审区），保持原顺序；
 *   - `staged`：durable + uncertain 的**原顺序**合并 —— 待审区要的就是这批（临时条不进批次）
 */
export function partitionTransient(facts) {
  /** @type {unknown[]} */
  const kept = [];
  /** @type {{ text: string, hit: string }[]} */
  const dropped = [];
  /** @type {{ text: string, hit: string }[]} */
  const deferred = [];
  /** @type {unknown[]} */
  const staged = [];
  for (const fact of Array.isArray(facts) ? facts : []) {
    if (typeof fact !== 'string') {
      kept.push(fact);
      staged.push(fact);
      continue;
    }
    const { verdict, hit } = looksTransient(fact);
    if (verdict === 'transient') {
      dropped.push({ text: fact, hit });
      continue;
    }
    if (verdict === 'uncertain') {
      deferred.push({ text: fact, hit });
    } else {
      kept.push(fact);
    }
    staged.push(fact);
  }
  return { kept, dropped, deferred, staged };
}
